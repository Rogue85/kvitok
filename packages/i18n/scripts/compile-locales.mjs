#!/usr/bin/env node
/**
 * Compiles the YAML catalogs in `locales/` into `src/generated/messages.ts`:
 * a `Messages` interface derived from `en.yaml` and one typed constant per language,
 * so a missing or extra key in any language fails type checking.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const PLURAL_CATEGORIES = new Set(['zero', 'one', 'two', 'few', 'many', 'other']);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalogs = Object.fromEntries(
  readdirSync(join(root, 'locales'))
    .filter((file) => file.endsWith('.yaml'))
    .sort()
    .map((file) => [file.replace(/\.yaml$/, ''), parse(readFileSync(join(root, 'locales', file), 'utf8'))]),
);

const isPlural = (node) =>
  typeof node === 'object' && node !== null && 'other' in node && Object.keys(node).every((key) => PLURAL_CATEGORIES.has(key));

function typeOf(node, indent) {
  if (typeof node === 'string') return 'string';
  if (isPlural(node)) return 'PluralForms';
  const pad = '  '.repeat(indent + 1);
  const fields = Object.entries(node).map(([key, value]) => `${pad}${JSON.stringify(key)}: ${typeOf(value, indent + 1)};`);
  return `{\n${fields.join('\n')}\n${'  '.repeat(indent)}}`;
}

const source = [
  '// Generated by scripts/compile-locales.mjs from locales/*.yaml. Do not edit: change the YAML instead.',
  "import type { PluralForms } from '../plural';",
  '',
  `export interface Messages ${typeOf(catalogs.en, 0)}`,
  '',
  ...Object.entries(catalogs).map(([locale, messages]) => `export const ${locale}: Messages = ${JSON.stringify(messages, null, 2)};\n`),
].join('\n');

mkdirSync(join(root, 'src', 'generated'), { recursive: true });
writeFileSync(join(root, 'src', 'generated', 'messages.ts'), source);
